use super::*;
use std::collections::BTreeSet;
pub(super) fn emit(
    cx: &mut PluginContext<'_, Swift>,
    input: &EventOperations,
    symbols: &BTreeMap<String, ModelSymbol>,
    module: &str,
) -> Result<BTreeMap<String, KafkaOperationSymbols>> {
    ensure!(
        input.operations.len() <= 10000,
        "Swift Kafka operation count exceeds 10000"
    );
    let reserved = [
        "KafkaRuntime",
        "KafkaSubscription",
        "KafkaDefinition",
        "KafkaRecord",
        "KafkaDelivery",
        "KafkaDefaults",
        "KafkaError",
        "KafkaSchema",
        "KafkaJSON",
        "KafkaMessages",
        "KafkaNativeClient",
        "KafkaNativeMessage",
        "KafkaWire",
    ];
    let mut used: BTreeSet<String> = reserved.iter().map(|v| v.to_lowercase()).collect();
    for symbol in symbols.values() {
        ensure!(
            safe_model_path(&symbol.module, module),
            "Swift Kafka models must belong to selected package module"
        );
        ensure!(
            safe_model_identifier(&symbol.name),
            "Swift Kafka selected model has an unsafe identifier: {}",
            symbol.name
        );
        ensure!(
            used.insert(symbol.name.to_lowercase()),
            "Swift Kafka model name collides with runtime: {}",
            symbol.name
        );
    }
    let mut operations = BTreeMap::new();
    for op in &input.operations {
        let class = format!("{}Event", crate::http::type_name(&op.name));
        ensure!(
            class.len() <= 160 && used.insert(class.to_lowercase()),
            "Swift Kafka operation name collision or filename budget: {}",
            op.name
        );
        let payload = symbols[&format!("{}/payload", op.message.location)].clone();
        let headers = op
            .message
            .headers
            .as_ref()
            .map(|_| symbols[&format!("{}/headers", op.message.location)].clone());
        let key = op
            .message
            .key
            .as_ref()
            .map(|_| symbols[&format!("{}/key", op.message.location)].clone());
        let p = &payload.name;
        let h = headers
            .as_ref()
            .map(|s| s.name.as_str())
            .unwrap_or("[String: String]");
        let k = key.as_ref().map(|s| s.name.as_str()).unwrap_or("String");
        let topic = literal(&serde_json::Value::String(op.topic.clone()));
        let client = op
            .client_id
            .as_ref()
            .map(|s| literal(&serde_json::Value::String(s.clone())))
            .unwrap_or("nil".into());
        let group = op
            .group_id
            .as_ref()
            .map(|s| literal(&serde_json::Value::String(s.clone())))
            .unwrap_or("nil".into());
        let ps = literal(&serde_json::Value::String(serde_json::to_string(
            &op.message.payload_schema,
        )?));
        let hs = op
            .message
            .headers_schema
            .as_ref()
            .map(|s| {
                literal(&serde_json::Value::String(
                    serde_json::to_string(s).unwrap(),
                ))
            })
            .unwrap_or("nil".into());
        let ks = op
            .message
            .key_schema
            .as_ref()
            .map(|s| {
                literal(&serde_json::Value::String(
                    serde_json::to_string(s).unwrap(),
                ))
            })
            .unwrap_or("nil".into());
        let method = match op.action {
            EventAction::Send => format!(
                "    public static func send(_ runtime: KafkaRuntime, payload: {p}, headers: {h}? = nil, key: {k}? = nil) async throws -> KafkaDelivery {{\n        try await runtime.send(definition, payload: payload, headers: headers, key: key)\n    }}"
            ),
            EventAction::Receive => format!(
                "    public static func subscribe(_ runtime: KafkaRuntime, group: String? = nil) async throws -> KafkaSubscription<{p}, {h}, {k}> {{\n        try await runtime.subscribe(definition, group: group)\n    }}"
            ),
        };
        let source = format!(
            "// Generated by Poolster.\nimport Foundation\n\npublic enum {class} {{\n    public static var definition: KafkaDefinition<{p}, {h}, {k}> {{\n        KafkaDefinition(topic: {topic}, clientID: {client}, group: {group}, payloadSchema: {ps}, headersSchema: {hs}, keySchema: {ks})\n    }}\n{method}\n}}\n"
        );
        ensure!(
            source.len() <= 128 * 1024,
            "Swift Kafka operation exceeds 128 KiB source budget"
        );
        let path = PathBuf::from(format!("Sources/{module}/{class}.swift"));
        cx.files.emit(GeneratedFile::new(&path, source)?)?;
        operations.insert(
            op.name.clone(),
            KafkaOperationSymbols {
                method: class,
                module: path,
                payload,
                headers,
                key,
                action: op.action,
            },
        );
    }
    let brokers = literal(&serde_json::Value::String(input.broker.brokers.join(",")));
    let client = literal(&serde_json::Value::String(
        input
            .broker
            .client_id
            .clone()
            .unwrap_or("poolster-swift".into()),
    ));
    cx.files.emit(GeneratedFile::new(format!("Sources/{module}/KafkaDefaults.swift"), format!("public enum KafkaDefaults {{\n    public static func connect() -> KafkaRuntime {{ KafkaRuntime(brokers: {brokers}, clientID: {client}) }}\n}}\n"))?)?;
    Ok(operations)
}
fn literal(value: &serde_json::Value) -> String {
    let mut output = String::from("\"");
    for character in value.as_str().expect("Swift literals are strings").chars() {
        match character {
            '\\' => output.push_str("\\\\"),
            '\"' => output.push_str("\\\""),
            '\n' => output.push_str("\\n"),
            '\r' => output.push_str("\\r"),
            '\t' => output.push_str("\\t"),
            character if character.is_control() || matches!(character, '\u{2028}' | '\u{2029}') => {
                output.push_str(&format!("\\u{{{:x}}}", character as u32))
            }
            character => output.push(character),
        }
    }
    output.push('\"');
    output
}

fn safe_model_path(path: &std::path::Path, module: &str) -> bool {
    path.components()
        .all(|part| matches!(part, std::path::Component::Normal(_)))
        && path.starts_with(std::path::Path::new("Sources").join(module))
        && path
            .extension()
            .is_some_and(|extension| extension == "swift")
}

fn safe_model_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|c| c == '_' || c.is_ascii_alphabetic())
        && chars.all(|c| c == '_' || c.is_ascii_alphanumeric())
        && ![
            "class",
            "struct",
            "enum",
            "protocol",
            "extension",
            "actor",
            "associatedtype",
            "typealias",
            "import",
            "let",
            "var",
            "func",
            "init",
            "deinit",
            "subscript",
            "public",
            "private",
            "internal",
            "fileprivate",
            "open",
            "static",
            "case",
            "default",
            "switch",
            "if",
            "else",
            "for",
            "while",
            "return",
            "throw",
            "throws",
            "try",
            "catch",
            "do",
            "in",
            "is",
            "as",
            "self",
            "Self",
            "super",
            "true",
            "false",
            "nil",
            "Any",
            "some",
            "any",
        ]
        .contains(&name)
}

#[cfg(test)]
mod provider_tests {
    use super::*;
    #[test]
    fn selected_model_paths_allow_nested_sources_without_traversal() {
        for path in [
            "Sources/SDK/Foo.swift",
            "Sources/SDK/models/Foo.swift",
            "Sources/SDK/models/nested/Foo.swift",
        ] {
            assert!(safe_model_path(std::path::Path::new(path), "SDK"));
        }
        for path in [
            "/Sources/SDK/Foo.swift",
            "Sources/SDK/../Other/Foo.swift",
            "Sources/SDK/models/../../Foo.swift",
            "Sources/Other/Foo.swift",
            "Sources/SDK/Foo.txt",
        ] {
            assert!(!safe_model_path(std::path::Path::new(path), "SDK"));
        }
        for name in ["ProviderPayload", "_Model", "Model2"] {
            assert!(safe_model_identifier(name));
        }
        for name in [
            "",
            "class",
            "2Model",
            "Model.Foo",
            "Model;fatalError()",
            "Model\n",
        ] {
            assert!(!safe_model_identifier(name));
        }
    }
}
