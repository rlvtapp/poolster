//! Protocol-neutral model output. No HTTP or GraphQL context is synthesized.
use crate::{TypeScript, models};
use anyhow::Result;
use poolster_core::{
    GeneratedFile,
    blocks::{Blocks, ModelBlock},
    engine::{Handle, PluginContext},
    models::{ModelOutput, ModelPlan, ModelPlugin, ModelSymbol},
};
use std::collections::{BTreeMap, BTreeSet};

pub fn shared_models(provider: Option<Handle<Blocks<ModelBlock>>>) -> ModelPlugin<TypeScript> {
    ModelPlugin::new(provider)
}

impl ModelOutput for TypeScript {
    const MODEL_CONTRACT_NAME: &'static str = "poolster.typescript.shared-models.v1";
    fn emit_models(
        cx: &mut PluginContext<'_, Self>,
        plan: &ModelPlan,
    ) -> Result<BTreeMap<String, ModelSymbol>> {
        let names = plan
            .schemas
            .iter()
            .map(|s| (s.name.clone(), s.name.clone()))
            .collect();
        let mut symbols = BTreeMap::new();
        let mut manifest = BTreeMap::new();
        for schema in &plan.schemas {
            let stem = models::schema_file_identifier(&schema.name);
            let module = std::path::PathBuf::from("shared-models").join(&stem);
            let path = module.with_extension("ts");
            let mut references = BTreeSet::new();
            models::collect_references(&schema.value, &mut references);
            references.remove(&schema.name);
            let notice = models::reference_notice(
                "/** Generated by Poolster. */\n",
                &path.to_string_lossy(),
                "shared-models",
                &references,
                &names,
            )?;
            cx.files.emit(GeneratedFile::new(
                &path,
                models::render_schema(
                    &schema.name,
                    &schema.value,
                    &models::ModelOptions::default(),
                    &notice,
                ),
            )?)?;
            cx.workspace
                .declare(&module, &schema.name, "typescript-shared-models")?;
            cx.workspace.export(&module)?;
            manifest.insert(schema.name.clone(), &schema.value);
            symbols.insert(
                schema.name.clone(),
                ModelSymbol {
                    name: schema.name.clone(),
                    module,
                },
            );
        }
        cx.files.emit(GeneratedFile::new(
            "shared-models/schema-manifest.json",
            serde_json::to_string_pretty(&manifest)?,
        )?)?;
        cx.files.emit(GeneratedFile::new("shared-models/README.md", "# Shared models\n\nThese TypeScript declarations describe wire data shapes. Constraints and extensions are retained in schema-manifest.json; TypeScript types do not validate runtime values. No broker or transport is generated by this plugin.\n")?)?;
        cx.workspace.default_package_file(GeneratedFile::new(
            "package.json",
            serde_json::to_string_pretty(&serde_json::json!({
                "name": cx.settings.package_name.as_deref().unwrap_or("poolster-shared-models"),
                "version": cx.common.package_version.as_deref().unwrap_or("0.0.0"),
                "type":"module", "main":"./dist/index.js", "types":"./dist/index.d.ts",
                "exports":{".":{"types":"./dist/index.d.ts","import":"./dist/index.js"}},
                "scripts":{"build":"tsc -p tsconfig.json"}, "devDependencies":{"typescript":"5.9.3"}
            }))?,
        )?)?;
        cx.workspace.default_package_file(GeneratedFile::new("tsconfig.json", "{\"compilerOptions\":{\"target\":\"ES2022\",\"module\":\"NodeNext\",\"moduleResolution\":\"NodeNext\",\"strict\":true,\"declaration\":true,\"outDir\":\"dist\"},\"include\":[\"**/*.ts\"],\"exclude\":[\"dist\"]}")?)?;
        Ok(symbols)
    }
}
