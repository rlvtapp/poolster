use super::*;
use std::collections::BTreeSet;
pub(super) fn emit(
    cx: &mut PluginContext<'_, Ruby>,
    input: &EventOperations,
    symbols: &BTreeMap<String, ModelSymbol>,
    package: &str,
) -> Result<BTreeMap<String, KafkaOperationSymbols>> {
    ensure!(
        input.operations.len() <= 10000,
        "Ruby Kafka operation count exceeds 10000"
    );
    let namespace = crate::pascal_case(package);
    let library = crate::snake_case(package);
    let root = format!("lib/{library}");
    let mut used = BTreeSet::new();
    let mut index = "# Generated by Poolster.\nrequire_relative 'events/runtime'\n".to_owned();
    let mut operations = BTreeMap::new();
    for op in &input.operations {
        let name = crate::pascal_case(&op.name);
        let file = crate::snake_case(&op.name);
        ensure!(
            ![
                "Runtime",
                "Codec",
                "Subscription",
                "Callback",
                "KafkaClient",
                "KafkaDefinition",
                "KafkaRecord",
                "KafkaSubscription",
                "KafkaCodec",
                "KafkaCallback"
            ]
            .contains(&name.as_str()),
            "event operation name collides with a runtime symbol: {}",
            op.name
        );
        ensure!(
            file.len() <= 160 && used.insert(file.clone()),
            "Ruby Kafka operation filenames collide or exceed budget"
        );
        let payload = symbols[&format!("{}/payload", op.message.location)].clone();
        let headers = op
            .message
            .headers
            .as_ref()
            .map(|_| symbols[&format!("{}/headers", op.message.location)].clone());
        let key = op
            .message
            .key
            .as_ref()
            .map(|_| symbols[&format!("{}/key", op.message.location)].clone());
        let mut requires = "require_relative 'runtime'\n".to_owned();
        for symbol in [Some(&payload), headers.as_ref(), key.as_ref()]
            .into_iter()
            .flatten()
        {
            ensure!(
                symbol.module.starts_with(format!("{root}/models"))
                    && symbol
                        .module
                        .components()
                        .all(|c| matches!(c, std::path::Component::Normal(_)))
                    && symbol.module.extension().is_some_and(|s| s == "rb"),
                "Ruby event model module must belong to selected package"
            );
            ensure!(
                symbol.name.starts_with(&format!("{namespace}::Models::"))
                    && symbol.name.split("::").all(|s| crate::pascal_case(s) == s),
                "Ruby event model symbol is not a safe package identifier"
            );
            let relative = symbol.module.strip_prefix(&root)?.to_string_lossy();
            requires.push_str(&format!(
                "require_relative {}\n",
                literal(&format!("../{relative}"))
            ));
        }
        let ty = |s: Option<&ModelSymbol>| s.map(|s| s.name.clone()).unwrap_or("nil".into());
        let client = op.client_id.as_ref().or(input.broker.client_id.as_ref());
        let definition = serde_json::json!({"topic":op.topic,"client_id":client,"group_id":op.group_id,"payload_schema":op.message.payload_schema,"headers_schema":op.message.headers_schema,"key_schema":op.message.key_schema});
        let json = literal(&serde_json::to_string(&definition)?);
        let method = match op.action {
            EventAction::Send => "      def self.send(client, payload, headers: nil, key: nil, timeout: 30)\n        client.send_event(DEFINITION, payload, headers: headers, key: key, timeout: timeout)\n      end\n".to_owned(),
            EventAction::Receive => "      def self.subscribe(client, group: nil)\n        client.subscribe(DEFINITION, group: group)\n      end\n".to_owned(),
        };
        let source = format!(
            "{requires}\nmodule {namespace}\n  module Events\n    module {name}\n      DEFINITION = KafkaDefinition.new(JSON.parse({json}), {}, {}, {})\n{method}    end\n  end\nend\n",
            ty(Some(&payload)),
            ty(headers.as_ref()),
            ty(key.as_ref())
        );
        ensure!(
            source.len() <= 128 * 1024,
            "Ruby Kafka operation source exceeds budget"
        );
        let module = PathBuf::from(format!("{root}/events/{file}.rb"));
        cx.files.emit(GeneratedFile::new(&module, source)?)?;
        index.push_str(&format!("require_relative 'events/{file}'\n"));
        operations.insert(
            op.name.clone(),
            KafkaOperationSymbols {
                method: format!("{namespace}::Events::{name}"),
                module,
                payload,
                headers,
                key,
                action: op.action,
            },
        );
    }
    index.push_str(&format!("\nmodule {namespace}\n  module Events\n    def self.connect(brokers: {})\n      KafkaClient.new(brokers: brokers)\n    end\n  end\nend\n",literal(&input.broker.brokers.join(","))));
    cx.files
        .emit(GeneratedFile::new(format!("{root}/events.rb"), index)?)?;
    for (file, template) in [
        ("runtime", include_str!("runtime.rb.tmpl")),
        ("codec", include_str!("codec.rb.tmpl")),
        ("subscription", include_str!("subscription.rb.tmpl")),
    ] {
        cx.files.emit(GeneratedFile::new(
            format!("{root}/events/{file}.rb"),
            template.replace("__NAMESPACE__", &namespace),
        )?)?;
    }
    Ok(operations)
}

fn literal(value: &str) -> String {
    format!("'{}'", value.replace('\\', "\\\\").replace('\'', "\\'"))
}
