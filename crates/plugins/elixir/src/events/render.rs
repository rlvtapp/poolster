use super::*;
use std::collections::BTreeSet;
pub(super) fn emit(
    cx: &mut PluginContext<'_, Elixir>,
    input: &EventOperations,
    symbols: &BTreeMap<String, ModelSymbol>,
    package: &str,
) -> Result<BTreeMap<String, KafkaOperationSymbols>> {
    ensure!(
        input.operations.len() <= 10000,
        "Elixir Kafka operation count exceeds 10000"
    );
    let namespace = crate::pascal_case(package);
    let library = crate::snake_case(package);
    let root = format!("lib/{library}");
    let mut used = BTreeSet::new();
    let mut operations = BTreeMap::new();
    for op in &input.operations {
        let class = crate::pascal_case(&op.name);
        let file = crate::snake_case(&op.name);
        ensure!(
            ![
                "Runtime",
                "Codec",
                "Subscription",
                "Callback",
                "KafkaClient",
                "KafkaDefinition",
                "KafkaRecord",
                "KafkaSubscription",
                "KafkaCodec",
                "KafkaCallback"
            ]
            .contains(&class.as_str()),
            "event operation name collides with a runtime symbol: {}",
            op.name
        );
        ensure!(
            file.len() <= 160 && used.insert(file.clone()),
            "Elixir Kafka operation filenames collide or exceed budget"
        );
        let payload = symbols[&format!("{}/payload", op.message.location)].clone();
        let headers = op
            .message
            .headers
            .as_ref()
            .map(|_| symbols[&format!("{}/headers", op.message.location)].clone());
        let key = op
            .message
            .key
            .as_ref()
            .map(|_| symbols[&format!("{}/key", op.message.location)].clone());
        for symbol in [Some(&payload), headers.as_ref(), key.as_ref()]
            .into_iter()
            .flatten()
        {
            ensure!(
                symbol.module.starts_with(format!("{root}/models"))
                    && symbol
                        .module
                        .components()
                        .all(|c| matches!(c, std::path::Component::Normal(_)))
                    && symbol.module.extension().is_some_and(|s| s == "ex"),
                "Elixir event model module must belong to selected package"
            );
            ensure!(
                symbol.name.starts_with(&format!("{namespace}.Models."))
                    && symbol.name.split('.').all(|s| crate::pascal_case(s) == s),
                "Elixir event model symbol is not a safe package identifier"
            );
        }
        let ty = |s: Option<&ModelSymbol>| s.map(|s| s.name.clone()).unwrap_or("nil".into());
        let json=serde_json::to_string(&serde_json::to_string(&serde_json::json!({"topic":op.topic,"client_id":op.client_id.as_ref().or(input.broker.client_id.as_ref()),"group_id":op.group_id,"payload_schema":op.message.payload_schema,"headers_schema":op.message.headers_schema,"key_schema":op.message.key_schema}))?)?.replace("#{", "\\#{");
        let method=match op.action {
            EventAction::Send=>"  def send(client, payload, options \\\\ []) do\n    __NAMESPACE__.Events.KafkaClient.send_event(client, definition(), payload, options)\n  end\n",
            EventAction::Receive=>"  def subscribe(client, options \\\\ []) do\n    __NAMESPACE__.Events.KafkaClient.subscribe(client, definition(), options)\n  end\n",
        }.replace("__NAMESPACE__",&namespace);
        let source = format!(
            "# Generated by Poolster.\ndefmodule {namespace}.Events.{class} do\n  @wire Jason.decode!({json})\n  def definition, do: %{{wire: @wire, payload_type: {}, headers_type: {}, key_type: {}}}\n{method}end\n",
            ty(Some(&payload)),
            ty(headers.as_ref()),
            ty(key.as_ref())
        );
        ensure!(
            source.len() <= 128 * 1024,
            "Elixir Kafka operation exceeds source budget"
        );
        let module = PathBuf::from(format!("{root}/events/{file}.ex"));
        cx.files.emit(GeneratedFile::new(&module, source)?)?;
        operations.insert(
            op.name.clone(),
            KafkaOperationSymbols {
                method: format!("{namespace}.Events.{class}"),
                module,
                payload,
                headers,
                key,
                action: op.action,
            },
        );
    }
    let brokers = serde_json::to_string(&input.broker.brokers)?.replace("#{", "\\#{");
    cx.files.emit(GeneratedFile::new(format!("{root}/events.ex"),format!("defmodule {namespace}.Events do\n  def connect(options \\\\ []), do: {namespace}.Events.KafkaClient.start_link(Keyword.put_new(options, :brokers, {brokers}))\nend\n"))?)?;
    let slots = (0..64)
        .map(|n| format!(":\"poolster.{namespace}.kafka.{n}\""))
        .collect::<Vec<_>>()
        .join(",\n    ");
    for (file, template) in [
        ("runtime", include_str!("runtime.ex.tmpl")),
        ("codec", include_str!("codec.ex.tmpl")),
        ("subscription", include_str!("subscription.ex.tmpl")),
        ("callback", include_str!("callback.ex.tmpl")),
    ] {
        cx.files.emit(GeneratedFile::new(
            format!("{root}/events/{file}.ex"),
            template
                .replace("__NAMESPACE__", &namespace)
                .replace("__SLOTS__", &slots),
        )?)?;
    }
    Ok(operations)
}
