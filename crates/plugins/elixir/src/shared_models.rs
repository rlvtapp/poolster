//! Models-only output over Poolster-owned block contracts.
use crate::*;
use poolster_core::{
    blocks::{Blocks, ModelBlock},
    engine::{Handle, PluginContext},
    models::{ModelOutput, ModelPlan, ModelPlugin, ModelSymbol},
};

pub fn shared_models(provider: Option<Handle<Blocks<ModelBlock>>>) -> ModelPlugin<Elixir> {
    ModelPlugin::new(provider)
}

impl ModelOutput for Elixir {
    const MODEL_CONTRACT_NAME: &'static str = "poolster.elixir.shared-models.v1";
    fn emit_models(
        cx: &mut PluginContext<Self>,
        plan: &ModelPlan,
    ) -> Result<BTreeMap<String, ModelSymbol>> {
        let package = cx
            .settings
            .package_name
            .as_deref()
            .unwrap_or("poolster_models");
        let module = pascal_case(package);
        let library = snake_case(package);
        let root = format!("lib/{library}");
        let runtime = format!(
            "# Generated by Poolster.\ndefmodule {module}.JSON do\n  def to_wire(value) when is_list(value), do: Enum.map(value, &to_wire/1)\n  def to_wire(value) when is_map(value) do\n    if is_struct(value) and function_exported?(value.__struct__, :to_map, 1) do\n      value.__struct__.to_map(value)\n    else\n      Map.new(value, fn {{key, item}} -> {{key, to_wire(item)}} end)\n    end\n  end\n  def to_wire(value), do: value\nend\n"
        );
        cx.files
            .emit(GeneratedFile::new(format!("{root}/json.ex"), runtime)?)?;
        let mut symbols = BTreeMap::new();
        for schema in &plan.schemas {
            supported(&schema.value)?;
            let name = pascal_case(&schema.name);
            let path = format!("{root}/models/{}.ex", snake_case(&schema.name));
            cx.files.emit(GeneratedFile::new(
                &path,
                validation::checked_model(&module, schema, plan),
            )?)?;
            symbols.insert(
                schema.name.clone(),
                ModelSymbol {
                    name: format!("{module}.Models.{name}"),
                    module: path.into(),
                },
            );
        }
        cx.workspace.models = true;
        Ok(symbols)
    }
}

fn supported(value: &SchemaValue) -> Result<()> {
    anyhow::ensure!(
        value.default.is_none(),
        "shared models do not support schema defaults in this language yet"
    );
    anyhow::ensure!(
        value.const_value.is_none() && value.enum_values.is_empty(),
        "shared models do not yet support literal/enum declarations in this language"
    );
    match &value.kind {
        SchemaKind::Object {
            fields,
            additional_properties,
        } => {
            for field in fields {
                supported(&field.value)?;
            }
            if let AdditionalProperties::Schema { value } = additional_properties {
                supported(value)?;
            }
        }
        SchemaKind::Array { items } => supported(items)?,
        SchemaKind::OneOf { .. } | SchemaKind::AnyOf { .. } => {
            anyhow::bail!("shared models do not yet support union declarations in this language")
        }
        SchemaKind::AllOf { .. } | SchemaKind::Not { .. } => {
            anyhow::bail!("shared models do not support intersection/negation declarations")
        }
        _ => {}
    }
    Ok(())
}

