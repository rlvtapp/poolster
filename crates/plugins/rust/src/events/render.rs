//! Per-operation declarations reference the shared generated model symbols.
use super::*;
use std::fmt::Write;
pub(super) fn emit(
    cx: &mut PluginContext<'_, Rust>,
    events: &EventOperations,
    models: &BTreeMap<String, EventModelSymbols>,
) -> Result<BTreeMap<String, KafkaOperationSymbols>> {
    let mut names = std::collections::BTreeSet::new();
    let mut index = String::from(
        "pub mod runtime;\npub use runtime::{KafkaClient, Subscription, KafkaMessage, ReceivedMessage, Publisher, Subscriber, RawMessage, MessageMetadata, Delivery, Error};\n",
    );
    let mut symbols = BTreeMap::new();
    let mut operations = events.operations.iter().collect::<Vec<_>>();
    operations.sort_by(|a, b| a.name.cmp(&b.name));
    let mut groups = BTreeMap::<usize, String>::new();
    for (i, op) in operations.into_iter().enumerate() {
        let name = validation::identifier(&op.name)?;
        ensure!(
            names.insert(name.clone()),
            "Rust Kafka operation filename collision {name}"
        );
        let model = &models[&op.message.location];
        for symbol in [
            Some(&model.payload),
            model.headers.as_ref(),
            model.key.as_ref(),
        ]
        .into_iter()
        .flatten()
        {
            ensure!(
                symbol.module.starts_with("src/models")
                    && !symbol.name.is_empty()
                    && symbol
                        .name
                        .chars()
                        .all(|c| c.is_ascii_alphanumeric() || c == '_'),
                "Rust event models must be local crate::models symbols"
            );
        }
        let payload = format!("crate::models::{}", model.payload.name);
        let headers = model
            .headers
            .as_ref()
            .map(|s| format!("crate::models::{}", s.name))
            .unwrap_or("std::collections::BTreeMap<String, String>".into());
        let key = model
            .key
            .as_ref()
            .map(|s| format!("crate::models::{}", s.name))
            .unwrap_or("String".into());
        let pascal = crate::render::type_name(&op.name);
        let source = format!(
            "// Generated by Poolster.\nuse crate::events::runtime::*;\npub type {pascal}Message = KafkaMessage<\n    {payload},\n    {headers},\n    {key},\n>;\nfn definition() -> Result<&'static Definition, Error> {{\n    static DEFINITION: std::sync::OnceLock<Result<Definition, String>> = std::sync::OnceLock::new();\n    DEFINITION.get_or_init(|| Definition::new(\n        {topic:?},\n        include_str!(\"../schemas/{name}_payload.json\"),\n        {headers_schema},\n        {key_schema},\n    ).map(|definition| definition.with_client_id({client_id})).map_err(|error| error.to_string())).as_ref().map_err(|error| Error::Schema(error.clone()))\n}}\n",
            topic = op.topic,
            client_id = op
                .client_id
                .as_ref()
                .map(|id| format!("Some({id:?})"))
                .unwrap_or("None".into()),
            headers_schema = if op.message.headers_schema.is_some() {
                format!("Some(include_str!(\"../schemas/{name}_headers.json\"))")
            } else {
                "None".into()
            },
            key_schema = if op.message.key_schema.is_some() {
                format!("Some(include_str!(\"../schemas/{name}_key.json\"))")
            } else {
                "None".into()
            }
        );
        let source = if op.action == EventAction::Send {
            format!(
                "{source}pub async fn {name}<T: Publisher>(client: &T, message: &{pascal}Message) -> Result<Delivery, Error> {{\n    publish(client, definition()?, message).await\n}}\nimpl KafkaClient {{\n    pub async fn {name}(&self, message: &{pascal}Message) -> Result<Delivery, Error> {{\n        {name}(self, message).await\n    }}\n}}\n"
            )
        } else {
            format!(
                "{source}pub async fn {name}<T: Subscriber>(subscription: &T) -> Result<ReceivedMessage<{payload}, {headers}, {key}>, Error> {{\n    receive(subscription, definition()?).await\n}}\nimpl KafkaClient {{\n    pub fn subscribe_{name}(&self) -> Result<Subscription, Error> {{\n        self.subscribe({topic:?}, {group}, {client_id})\n    }}\n}}\nimpl Subscription {{\n    pub async fn {name}(&self) -> Result<ReceivedMessage<{payload}, {headers}, {key}>, Error> {{\n        {name}(self).await\n    }}\n}}\n",
                topic = op.topic,
                group = op
                    .group_id
                    .as_ref()
                    .map(|s| format!("Some({s:?})"))
                    .unwrap_or("None".into()),
                client_id = op
                    .client_id
                    .as_ref()
                    .map(|s| format!("Some({s:?})"))
                    .unwrap_or("None".into())
            )
        };
        let path = PathBuf::from(format!("src/events/operations/{name}.rs"));
        cx.files.emit(GeneratedFile::new(&path, source)?)?;
        for (role, schema) in [
            ("payload", Some(&op.message.payload_schema)),
            ("headers", op.message.headers_schema.as_ref()),
            ("key", op.message.key_schema.as_ref()),
        ] {
            if let Some(schema) = schema {
                cx.files.emit(GeneratedFile::new(
                    format!("src/events/schemas/{name}_{role}.json"),
                    serde_json::to_string_pretty(schema)? + "\n",
                )?)?;
            }
        }
        writeln!(
            groups.entry(i / 100).or_default(),
            "#[path = \"../operations/{name}.rs\"]\npub mod {name};\npub use {name}::*;"
        )?;
        symbols.insert(
            op.name.clone(),
            KafkaOperationSymbols {
                function: name,
                module: path,
                payload: model.payload.clone(),
                headers: model.headers.clone(),
                key: model.key.clone(),
                action: op.action,
            },
        );
    }
    for (group, source) in groups {
        let module = format!("group_{group}");
        cx.files.emit(GeneratedFile::new(
            format!("src/events/groups/{module}.rs"),
            source,
        )?)?;
        writeln!(
            index,
            "#[path = \"groups/{module}.rs\"]\nmod {module};\npub use {module}::*;"
        )?;
    }

    cx.files
        .emit(GeneratedFile::new("src/events/mod.rs", index)?)?;
    cx.files.emit(GeneratedFile::new(
        "src/events/runtime/mod.rs",
        include_str!("runtime/mod.rs.tmpl"),
    )?)?;
    cx.files.emit(GeneratedFile::new(
        "src/events/runtime/codec.rs",
        include_str!("runtime/codec.rs.tmpl"),
    )?)?;
    cx.files.emit(GeneratedFile::new(
        "src/events/runtime/kafka.rs",
        include_str!("runtime/kafka.rs.tmpl")
            .replace(
                "__BROKERS__",
                &format!("{:?}", events.broker.brokers.join(",")),
            )
            .replace(
                "__CLIENT_ID__",
                &format!(
                    "{:?}",
                    events.broker.client_id.as_deref().unwrap_or("poolster")
                ),
            ),
    )?)?;
    cx.files.emit(GeneratedFile::new(
        "asyncapi.json",
        serde_json::to_string_pretty(&events.source)? + "\n",
    )?)?;
    cx.files.emit(GeneratedFile::new(
        "README.md",
        include_str!("runtime/README.md.tmpl"),
    )?)?;
    Ok(symbols)
}
