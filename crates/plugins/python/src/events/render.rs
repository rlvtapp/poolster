use super::*;
use crate::python_identifier;
use poolster_core::native::events::EventAction;
use std::fmt::Write;
pub(super) fn emit(
    cx: &mut PluginContext<Python>,
    input: &EventOperations,
    symbols: &BTreeMap<String, ModelSymbol>,
) -> Result<BTreeMap<String, ModelSymbol>> {
    let module = python_module_name(
        cx.settings
            .package_name
            .as_deref()
            .unwrap_or("poolster-models"),
    );
    let root = format!("src/{module}/events");
    cx.files.emit(GeneratedFile::new(
        format!("{root}/_runtime.py"),
        include_str!("runtime.py.tmpl"),
    )?)?;
    cx.files.emit(GeneratedFile::new(
        format!("{root}/_codec.py"),
        include_str!("codec.py.tmpl"),
    )?)?;
    let mut names = std::collections::BTreeSet::new();
    let mut operations = BTreeMap::new();
    let mut chunks = Vec::new();
    for (chunk_index, chunk) in input.operations.chunks(100).enumerate() {
        let mut imports = String::from("# Generated by Poolster. Do not edit.\n");
        let mut bases = Vec::new();
        for op in chunk {
            let name = python_identifier(&op.name);
            ensure!(
                names.insert(name.clone())
                    && !["close", "_send", "__init__"].contains(&name.as_str()),
                "Python Kafka operation name collision or reserved name: {name}"
            );
            let payload = &symbols[&format!("{}/payload", op.message.location)];
            let header = symbols.get(&format!("{}/headers", op.message.location));
            let mut source = String::from(
                "# Generated by Poolster. Do not edit.\nfrom __future__ import annotations\nimport json\nfrom threading import Event\nfrom ._runtime import Subscription\n",
            );
            for s in std::iter::once(payload).chain(header) {
                ensure!(
                    s.module.parent().and_then(|p| p.to_str())
                        == Some(&format!("src/{module}/models")),
                    "Python event shared models must be in the same package"
                );
                writeln!(
                    source,
                    "from ..models.{} import {}",
                    s.module.file_stem().unwrap().to_string_lossy(),
                    s.name
                )?;
            }
            let definition = serde_json::to_string(
                &serde_json::json!({"topic":op.topic,"payload":op.message.payload_schema,"headers":op.message.headers_schema,"key":op.message.key_schema,"client_id":op.client_id.clone().or(input.broker.client_id.clone()),"group_id":op.group_id}),
            )?;
            writeln!(
                source,
                "\n_DEFINITION = json.loads({definition:?})\n\nclass Operation:"
            )?;
            let payload_annotation = if op.message.payload.nullable {
                format!("{} | None", payload.name)
            } else {
                payload.name.clone()
            };
            let h = header.map(|s| s.name.as_str()).unwrap_or("dict[str, str]");
            if op.action == EventAction::Send {
                writeln!(
                    source,
                    "    def {name}(self, payload: {}, *, headers: {h} | None = None, key: str | None = None, timeout: float = 30.0):\n        return self._send(_DEFINITION, payload, headers, key, timeout)",
                    payload_annotation
                )?;
            } else {
                writeln!(
                    source,
                    "    def {name}(self, *, group_id: str | None = None, cancel: Event | None = None) -> Subscription[{}, {h}]:\n        if self._closed:\n            raise RuntimeError(\"Kafka client is closed\")\n        if group_id is not None and _DEFINITION[\"group_id\"] is not None and group_id != _DEFINITION[\"group_id\"]:\n            raise ValueError(\"group_id conflicts with the operation binding\")\n        return Subscription(self._brokers, _DEFINITION, group_id or _DEFINITION[\"group_id\"], cancel, {}, {h})",
                    payload_annotation, payload.name
                )?;
            }
            let file = format!("{root}/{name}.py");
            cx.files.emit(GeneratedFile::new(&file, source)?)?;
            let alias = format!("Op{}", bases.len());
            writeln!(imports, "from .{name} import Operation as {alias}")?;
            bases.push(alias);
            operations.insert(
                op.name.clone(),
                ModelSymbol {
                    name: name.clone(),
                    module: file.into(),
                },
            );
        }
        let class = format!("Operations{chunk_index}");
        writeln!(imports, "\nclass {class}({}):\n    pass", bases.join(", "))?;
        cx.files.emit(GeneratedFile::new(
            format!("{root}/_chunk_{chunk_index}.py"),
            imports,
        )?)?;
        chunks.push(class);
    }
    ensure!(
        chunks.len() <= 100,
        "Python Kafka supports at most 10000 operations per package"
    );
    let mut client =
        String::from("# Generated by Poolster. Do not edit.\nfrom ._runtime import Runtime\n");
    for (i, c) in chunks.iter().enumerate() {
        writeln!(client, "from ._chunk_{i} import {c}")?;
    }
    let bases = std::iter::once("Runtime".to_owned())
        .chain(chunks)
        .collect::<Vec<_>>()
        .join(", ");
    let brokers = serde_json::to_string(&input.broker.brokers)?;
    writeln!(
        client,
        "import json\n\nclass KafkaClient({bases}):\n    def __init__(self, brokers=None, *, retries: int = 0):\n        super().__init__(brokers or json.loads({brokers:?}), default_client_id={}, retries=retries)",
        input
            .broker
            .client_id
            .as_ref()
            .map(|v| format!("{v:?}"))
            .unwrap_or("None".into())
    )?;
    cx.files.emit(GeneratedFile::new(
        format!("{root}/__init__.py"),
        "from .client import KafkaClient\nfrom ._runtime import Record, Subscription\n",
    )?)?;
    cx.files
        .emit(GeneratedFile::new(format!("{root}/client.py"), client)?)?;
    cx.files.emit(GeneratedFile::new("README.md", format!("# {module}: Kafka JSON events\n\nInstall this package to install pinned kafka-python 3.0.11 and jsonschema 4.26.0.\nProvision static topics before use. Only plaintext Kafka, Draft-07 JSON payloads, closed string headers, and optional nonnullable string keys are supported.\nUse `KafkaClient` as a context manager. Send methods synchronously return broker metadata. Receive methods return context-managed `Subscription` iterators; call `record.ack()` after processing or `subscription.run(handler)` to commit after successful handlers. Exceptions never auto-commit. Cancellation uses a threading.Event, polled every 250 ms; close subscriptions explicitly.\nProducer retries default to zero. Opt-in `retries=N` can duplicate messages: there is no application idempotency, transaction or exactly-once guarantee. No consumer handler retry is added.\n"))?)?;
    Ok(operations)
}
