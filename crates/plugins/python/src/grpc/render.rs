use super::typing;
use anyhow::{Result, ensure};
use poolster_core::native::rpc::{RpcContract, RpcStreaming, RpcWireSchema};
use std::collections::BTreeSet;
pub(super) fn module(file: &str) -> String {
    format!("{}_pb2", file.trim_end_matches(".proto").replace('/', "."))
}
pub(super) fn literal(value: &str) -> String {
    serde_json::to_string(value).expect("serializable string")
}
pub(super) fn package(
    contract: &RpcContract,
    schema: &RpcWireSchema,
    files: &[String],
    name: &str,
    version: &str,
    options: &poolster_core::native::rpc::RpcGenerationOptions,
    style: poolster_core::native::rpc::RpcClientStyle,
) -> Result<Vec<(String, String)>> {
    ensure!(
        !version.is_empty()
            && version
                .bytes()
                .all(|c| c.is_ascii_alphanumeric() || b".+!-_".contains(&c)),
        "Python package version must be a portable PEP 440 version"
    );
    let id = name.replace(['-', '.'], "_").to_lowercase();
    let runtime = format!("_poolster_rpc_{id}");
    let descriptors = format!("_poolster_descriptors_{id}");
    let mut output = Vec::new();
    let metadata = schema.metadata()?;
    let mut raw = String::from(
        "# Generated by Poolster. Authoritative descriptor bytes in bounded modules.\n",
    );
    let mut parts = Vec::new();
    for (index, part) in contract.descriptor_set.chunks(8192).enumerate() {
        let part_module = format!("{descriptors}_part_{index}");
        raw.push_str(&format!(
            "from {part_module} import DATA as _part_{index}\n"
        ));
        parts.push(format!("_part_{index}"));
        let mut body =
            String::from("# Generated by Poolster. Descriptor byte segment.\nDATA = bytes([\n");
        for chunk in part.chunks(24) {
            body.push_str("    ");
            body.push_str(
                &chunk
                    .iter()
                    .map(u8::to_string)
                    .collect::<Vec<_>>()
                    .join(", "),
            );
            body.push_str(",\n");
        }
        body.push_str("])\n");
        output.push((format!("src/{part_module}.py"), body));
    }
    raw.push_str(&format!(
        "DESCRIPTOR_SET = {}\n",
        if parts.is_empty() {
            "b''".into()
        } else {
            parts.join(" + ")
        }
    ));
    output.push((format!("src/{descriptors}.py"), raw));
    let local = serde_json::to_string(files)?;
    output.push((
        format!("src/{runtime}.py"),
        include_str!("runtime.py.tmpl")
            .replace("{{DESCRIPTORS}}", &descriptors)
            .replace("{{LOCAL_FILES}}", &local)
            .replace(
                "{{MAX_MESSAGE_BYTES}}",
                &options.max_message_bytes.to_string(),
            )
            .replace("{{MAX_DEPTH}}", &options.max_depth.to_string())
            .replace(
                "{{DISCARD_UNKNOWN}}",
                if options.unknown_fields == poolster_core::native::rpc::RpcUnknownFields::Discard {
                    "True"
                } else {
                    "False"
                },
            ),
    ));
    if (options.emit_clients || options.emit_servers)
        && options
            .transports
            .iter()
            .any(|transport| *transport != poolster_core::native::rpc::RpcTransport::Grpc)
    {
        let methods: serde_json::Map<String, serde_json::Value> = schema
            .files
            .iter()
            .flat_map(|file| &file.services)
            .flat_map(|service| {
                service.methods.iter().map(move |method| {
                    let (_, input_stream, output_stream) = stream(method.streaming);
                    (
                        format!("{}/{}", service.full_name, method.name),
                        serde_json::json!([
                            method.input_type,
                            method.output_type,
                            input_stream,
                            output_stream
                        ]),
                    )
                })
            })
            .collect();
        let methods = serde_json::to_string(&methods)?;
        for (enabled, module, template) in [
            (
                options.emit_clients,
                format!("http_{id}"),
                include_str!("http.py.tmpl"),
            ),
            (
                options.emit_servers,
                format!("http_server_{id}"),
                include_str!("http_server.py.tmpl"),
            ),
        ] {
            if !enabled {
                continue;
            }
            let source = template
                .replace("{{RUNTIME}}", &runtime)
                .replace(
                    "{{METHODS}}",
                    &format!("_json.loads({})", literal(&methods)),
                )
                .replace("{{LIMIT}}", &options.max_message_bytes.to_string());
            output.push((format!("src/{module}.py"), source));
            if options.emit_types && module == format!("http_{id}") {
                output.push((
                    format!("src/{module}.pyi"),
                    super::http::annotations(schema, options)?,
                ));
            }
        }
    }
    if options.emit_clients && !options.batching.is_empty() {
        let methods: std::collections::BTreeMap<_, _> = schema
            .files
            .iter()
            .flat_map(|file| &file.services)
            .flat_map(|service| {
                service
                    .methods
                    .iter()
                    .map(move |method| (&method.full_name, (service, method)))
            })
            .collect();
        let mut mappings = serde_json::Map::new();
        for mapping in &options.batching {
            let (_, single) = methods[&mapping.single_method];
            let (service, batch) = methods[&mapping.batch_method];
            let mut value = serde_json::to_value(mapping)?;
            let object = value.as_object_mut().expect("serialized batch mapping");
            object.insert("singleInput".into(), single.input_type.clone().into());
            object.insert("batchInput".into(), batch.input_type.clone().into());
            object.insert("batchOutput".into(), batch.output_type.clone().into());
            object.insert(
                "route".into(),
                format!("/{}/{}", service.full_name, batch.name).into(),
            );
            mappings.insert(mapping.single_method.clone(), value);
        }
        let mappings = serde_json::to_string(&mappings)?;
        let source = include_str!("batching.py.tmpl")
            .replace("{{RUNTIME}}", &runtime)
            .replace(
                "{{MAPPINGS}}",
                &format!("_json.loads({})", literal(&mappings)),
            );
        output.push((format!("src/batching_{id}.py"), source));
        if options.emit_types {
            output.push((
                format!("src/batching_{id}.pyi"),
                super::batching::annotations(schema, options)?,
            ));
        }
    }
    if options.immutable_views || options.reactive_streams || options.value_adapters {
        let (source, annotations) = super::views::render(&runtime, schema, options)?;
        output.push((format!("src/views_{id}.py"), source));
        if options.emit_types {
            output.push((format!("src/views_{id}.pyi"), annotations));
        }
    }
    for file in &schema.files {
        if !files.contains(&file.name) {
            continue;
        }
        let documentation = metadata
            .iter()
            .find(|item| item.file == file.name)
            .filter(|_| options.comments)
            .map(super::presentation::documentation)
            .unwrap_or_default();
        let mut messages =
            format!("# Generated by Poolster.\n{documentation}import {runtime} as _runtime\n");
        for (index, dependency) in file.dependencies.iter().enumerate() {
            messages.push_str(&format!(
                "import {} as _dependency_{index}\n",
                super::presentation::module(dependency, options)
            ));
        }
        for dependency in &file.public_dependencies {
            messages.push_str(&format!(
                "from {} import *\n",
                super::presentation::module(dependency, options)
            ));
        }
        messages.push_str(&format!(
            "globals().update(_runtime.exports({}, __name__))\n",
            literal(&file.name)
        ));
        messages.push_str(&super::presentation::aliases(file, options));
        messages.push_str(&super::enum_aliases::render(file, options)?);
        output.push((
            format!(
                "src/{}.py",
                super::presentation::module(&file.name, options).replace('.', "/")
            ),
            messages,
        ));
        if options.emit_types {
            output.push((
                format!(
                    "src/{}.pyi",
                    super::presentation::module(&file.name, options).replace('.', "/")
                ),
                typing::messages(file, schema, options)?,
            ));
        }
        if !options.emit_clients && !options.emit_servers || file.services.is_empty() {
            continue;
        }
        let mut services = format!(
            "# Generated by Poolster.\nimport grpc\nimport {} as _messages\nimport {runtime} as _runtime\n\n",
            super::presentation::module(&file.name, options)
        );
        for service in &file.services {
            let short = service.full_name.rsplit('.').next().unwrap();
            if options.emit_clients {
                services.push_str(&format!(
                    "class {short}Stub:\n    def __init__(self, channel):\n"
                ));
                if service.methods.is_empty() {
                    services.push_str("        pass\n");
                }
                for method in &service.methods {
                    let (channel, _, _) = stream(method.streaming);
                    services.push_str(&format!("        self.{} = channel.{channel}(\n            {},\n            request_serializer=_runtime._encode,\n            response_deserializer=lambda data: _runtime._decode(_runtime.message({}), data),\n        )\n",method.name,literal(&format!("/{}/{}",service.full_name,method.name)),literal(&method.output_type)));
                }
                services.push_str(&format!("\nclass Async{short}Stub({short}Stub):\n    \"\"\"Native grpc.aio call objects; use with an aio channel.\"\"\"\n    pass\n"));
            }
            if options.emit_servers {
                services.push_str(&format!("\nclass {short}Servicer:\n"));
                if service.methods.is_empty() {
                    services.push_str("    pass\n");
                }
                for method in &service.methods {
                    services.push_str(&format!("    def {}(self, request, context):\n        context.abort(grpc.StatusCode.UNIMPLEMENTED, \"Method not implemented\")\n\n",method.name));
                }
                services.push_str(&format!("\nclass Async{short}Servicer:\n"));
                if service.methods.is_empty() {
                    services.push_str("    pass\n");
                }
                for method in &service.methods {
                    let (_, _, output_stream) = stream(method.streaming);
                    services.push_str(&format!("    async def {}(self, request, context):\n        await context.abort(grpc.StatusCode.UNIMPLEMENTED, \"Method not implemented\")\n", method.name));
                    if output_stream {
                        services.push_str("        if False:\n            yield None\n");
                    }
                    services.push('\n');
                }
                services.push_str(&format!(
                    "def add_{short}Servicer_to_server(servicer, server):\n    handlers = {{\n"
                ));
                for method in &service.methods {
                    let (channel, _, _) = stream(method.streaming);
                    services.push_str(&format!("        {}: grpc.{channel}_rpc_method_handler(\n            servicer.{},\n            request_deserializer=lambda data: _runtime._decode(_runtime.message({}), data),\n            response_serializer=_runtime._encode,\n        ),\n",literal(&method.name),method.name,literal(&method.input_type)));
                }
                services.push_str(&format!("    }}\n    server.add_generic_rpc_handlers((grpc.method_handlers_generic_handler({}, handlers),))\n    server.add_registered_method_handlers({}, handlers)\n\n",literal(&service.full_name),literal(&service.full_name)));
                services.push_str(&format!("def add_Async{short}Servicer_to_server(servicer, server):\n    add_{short}Servicer_to_server(servicer, server)\n\n"));
            }
        }
        output.push((
            format!(
                "src/{}_grpc.py",
                super::presentation::module(&file.name, options).replace('.', "/")
            ),
            services,
        ));
        if options.emit_types {
            output.push((
                format!(
                    "src/{}_grpc.pyi",
                    super::presentation::module(&file.name, options).replace('.', "/")
                ),
                typing::services(file, schema, options)?,
            ));
        }
    }
    if let Some((source, annotations)) = super::styles::render(schema, options, style)? {
        output.push((format!("src/client_{id}.py"), source));
        if options.emit_types {
            output.push((format!("src/client_{id}.pyi"), annotations));
        }
    }
    if options.emit_index {
        let mut index = String::from(
            "# Generated by Poolster. Native protocol modules retain their own namespaces.\n",
        );
        let mut names = BTreeSet::new();
        for file in &schema.files {
            if !files.contains(&file.name) {
                continue;
            }
            let name =
                crate::python_identifier(&file.name.trim_end_matches(".proto").replace('/', "_"));
            ensure!(
                names.insert(name.clone()),
                "Python Protobuf index namespace collision: {name}"
            );
            index.push_str(&format!(
                "import {} as {name}\n",
                super::presentation::module(&file.name, options)
            ));
            if !options.representations.is_native()
                && file.messages.iter().any(|message| !message.map_entry)
            {
                let native = super::presentation::module(&file.name, options);
                index.push_str(&format!(
                    "import {}_values as {name}_values\n",
                    native.trim_end_matches("_pb2")
                ));
            }
            if (options.emit_clients || options.emit_servers) && !file.services.is_empty() {
                index.push_str(&format!(
                    "import {}_grpc as {name}_rpc\n",
                    super::presentation::module(&file.name, options)
                ));
            }
        }
        if options.emit_clients && schema.files.iter().any(|file| !file.services.is_empty()) {
            index.push_str(&format!("import client_{id} as client\n"));
        }
        output.push((format!("src/poolster_rpc_{id}.py"), index.clone()));
        if options.emit_types {
            output.push((format!("src/poolster_rpc_{id}.pyi"), index));
        }
    }
    output.extend(super::values::render(
        schema, files, &runtime, &id, options,
    )?);
    super::assembly::Context {
        contract,
        schema,
        files,
        name,
        version,
        options,
        runtime: &runtime,
        id: &id,
    }
    .finish(&mut output)?;
    Ok(output)
}
pub(super) fn stream(kind: RpcStreaming) -> (&'static str, bool, bool) {
    match kind {
        RpcStreaming::Unary => ("unary_unary", false, false),
        RpcStreaming::Client => ("stream_unary", true, false),
        RpcStreaming::Server => ("unary_stream", false, true),
        RpcStreaming::Bidirectional => ("stream_stream", true, true),
    }
}
