use super::{GRPC_VERSION, PROTOBUF_VERSION, SETUPTOOLS_VERSION, typing};
use anyhow::{Result, ensure};
use poolster_core::native::rpc::{RpcContract, RpcStreaming, RpcWireSchema};
use std::collections::BTreeSet;
pub(super) fn module(file: &str) -> String {
    format!("{}_pb2", file.trim_end_matches(".proto").replace('/', "."))
}
fn path(file: &str, suffix: &str) -> String {
    format!("src/{}{suffix}", file.trim_end_matches(".proto"))
}
fn literal(value: &str) -> String {
    serde_json::to_string(value).expect("serializable string")
}
pub(super) fn package(
    contract: &RpcContract,
    schema: &RpcWireSchema,
    files: &[String],
    name: &str,
    version: &str,
) -> Result<Vec<(String, String)>> {
    ensure!(
        !version.is_empty()
            && version
                .bytes()
                .all(|c| c.is_ascii_alphanumeric() || b".+!-_".contains(&c)),
        "Python package version must be a portable PEP 440 version"
    );
    let id = name.replace(['-', '.'], "_").to_lowercase();
    let runtime = format!("_poolster_rpc_{id}");
    let descriptors = format!("_poolster_descriptors_{id}");
    let mut output = Vec::new();
    let mut raw = String::from(
        "# Generated by Poolster. Authoritative FileDescriptorSet bytes.\nDESCRIPTOR_SET = bytes([\n",
    );
    for chunk in contract.descriptor_set.chunks(24) {
        raw.push_str("    ");
        raw.push_str(
            &chunk
                .iter()
                .map(u8::to_string)
                .collect::<Vec<_>>()
                .join(", "),
        );
        raw.push_str(",\n");
    }
    raw.push_str("])\n");
    output.push((format!("src/{descriptors}.py"), raw));
    let local = serde_json::to_string(files)?;
    output.push((
        format!("src/{runtime}.py"),
        include_str!("runtime.py.tmpl")
            .replace("{{DESCRIPTORS}}", &descriptors)
            .replace("{{LOCAL_FILES}}", &local),
    ));
    for file in &schema.files {
        if !files.contains(&file.name) {
            continue;
        }
        let mut messages = format!("# Generated by Poolster.\nimport {runtime} as _runtime\n");
        for (index, dependency) in file.dependencies.iter().enumerate() {
            messages.push_str(&format!(
                "import {} as _dependency_{index}\n",
                module(dependency)
            ));
        }
        for dependency in &file.public_dependencies {
            messages.push_str(&format!("from {} import *\n", module(dependency)));
        }
        messages.push_str(&format!(
            "globals().update(_runtime.exports({}, __name__))\n",
            literal(&file.name)
        ));
        output.push((path(&file.name, "_pb2.py"), messages));
        output.push((
            path(&file.name, "_pb2.pyi"),
            typing::messages(file, schema)?,
        ));
        let mut services = format!(
            "# Generated by Poolster.\nimport grpc\nimport {} as _messages\nimport {runtime} as _runtime\n\n",
            module(&file.name)
        );
        for service in &file.services {
            let short = service.full_name.rsplit('.').next().unwrap();
            services.push_str(&format!(
                "class {short}Stub:\n    def __init__(self, channel):\n"
            ));
            if service.methods.is_empty() {
                services.push_str("        pass\n");
            }
            for method in &service.methods {
                let (channel, _, _) = stream(method.streaming);
                services.push_str(&format!("        self.{} = channel.{channel}(\n            {},\n            request_serializer=_runtime.message({}).SerializeToString,\n            response_deserializer=_runtime.message({}).FromString,\n        )\n",method.name,literal(&format!("/{}/{}",service.full_name,method.name)),literal(&method.input_type),literal(&method.output_type)));
            }
            services.push_str(&format!("\nclass {short}Servicer:\n"));
            if service.methods.is_empty() {
                services.push_str("    pass\n");
            }
            for method in &service.methods {
                services.push_str(&format!("    def {}(self, request, context):\n        context.abort(grpc.StatusCode.UNIMPLEMENTED, \"Method not implemented\")\n\n",method.name));
            }
            services.push_str(&format!(
                "def add_{short}Servicer_to_server(servicer, server):\n    handlers = {{\n"
            ));
            for method in &service.methods {
                let (channel, _, _) = stream(method.streaming);
                services.push_str(&format!("        {}: grpc.{channel}_rpc_method_handler(\n            servicer.{},\n            request_deserializer=_runtime.message({}).FromString,\n            response_serializer=_runtime.message({}).SerializeToString,\n        ),\n",literal(&method.name),method.name,literal(&method.input_type),literal(&method.output_type)));
            }
            services.push_str(&format!("    }}\n    server.add_generic_rpc_handlers((grpc.method_handlers_generic_handler({}, handlers),))\n    server.add_registered_method_handlers({}, handlers)\n\n",literal(&service.full_name),literal(&service.full_name)));
        }
        output.push((path(&file.name, "_pb2_grpc.py"), services));
        output.push((
            path(&file.name, "_pb2_grpc.pyi"),
            typing::services(file, schema)?,
        ));
    }
    let modules: BTreeSet<_> = files
        .iter()
        .filter(|f| !f.contains('/'))
        .flat_map(|f| {
            let stem = f.trim_end_matches(".proto");
            [format!("{stem}_pb2"), format!("{stem}_pb2_grpc")]
        })
        .chain([runtime, descriptors])
        .collect();
    let modules = modules
        .iter()
        .map(|m| literal(m))
        .collect::<Vec<_>>()
        .join(", ");
    let manifest = format!(
        "[build-system]\nrequires = [\"setuptools=={SETUPTOOLS_VERSION}\"]\nbuild-backend = \"setuptools.build_meta\"\n\n[project]\nname = {}\nversion = {}\nrequires-python = \">=3.10\"\ndependencies = [\"grpcio=={GRPC_VERSION}\", \"protobuf=={PROTOBUF_VERSION}\"]\n\n[tool.setuptools]\npackage-dir = {{\"\" = \"src\"}}\npy-modules = [{modules}]\ninclude-package-data = true\n\n[tool.setuptools.packages.find]\nwhere = [\"src\"]\nnamespaces = true\n\n[tool.setuptools.package-data]\n\"*\" = [\"*.pyi\", \"py.typed\"]\n",
        literal(name),
        literal(version)
    );
    output.push(("pyproject.toml".into(), manifest));
    output.push(("setup.py".into(), include_str!("setup.py.tmpl").into()));
    output.push((
        "MANIFEST.in".into(),
        "recursive-include src *.py *.pyi py.typed\n".into(),
    ));
    for file in files {
        if let Some((root, _)) = file.split_once('/') {
            let marker = format!("src/{root}/py.typed");
            if !output.iter().any(|(path, _)| path == &marker) {
                output.push((marker, String::new()));
            }
        }
    }
    for file in &contract.files {
        if let Some(source) = &file.source {
            output.push((format!("proto/{}", file.name), source.clone()));
        }
    }
    output.push((
        "proto/descriptor-set.json".into(),
        serde_json::to_string(&contract.descriptor_set)?,
    ));
    output.push(("README.md".into(), include_str!("README.md.tmpl").into()));
    Ok(output)
}
pub(super) fn stream(kind: RpcStreaming) -> (&'static str, bool, bool) {
    match kind {
        RpcStreaming::Unary => ("unary_unary", false, false),
        RpcStreaming::Client => ("stream_unary", true, false),
        RpcStreaming::Server => ("unary_stream", false, true),
        RpcStreaming::Bidirectional => ("stream_stream", true, true),
    }
}
