//! All facades reuse the same native stub callables and retain RPC identity.
use anyhow::{Result, ensure};
use poolster_core::native::rpc::{RpcClientStyle, RpcGenerationOptions, RpcWireSchema};
use std::collections::BTreeSet;
pub(super) fn render(
    schema: &RpcWireSchema,
    options: &RpcGenerationOptions,
    style: RpcClientStyle,
) -> Result<Option<(String, String)>> {
    if !options.emit_clients {
        return Ok(None);
    }
    let services: Vec<_> = schema
        .files
        .iter()
        .flat_map(|file| file.services.iter().map(move |service| (file, service)))
        .collect();
    if services.is_empty() {
        return Ok(None);
    }
    let types = super::typing::Types::configured("", schema, options);
    let mut code = String::from("# Generated by Poolster. Raw, flat and grouped RPC facades.\n");
    let mut annotations = String::from("# Generated by Poolster.\nimport grpc\n");
    annotations.push_str(&types.imports());
    let mut names = BTreeSet::new();
    let mut groups = BTreeSet::new();
    for (index, (file, service)) in services.iter().enumerate() {
        let name = service.full_name.rsplit('.').next().unwrap();
        let group = group_name(schema, &service.full_name);
        ensure!(
            groups.insert(group.clone()),
            "Python RPC service facade naming collision: {}",
            service.full_name
        );
        code.push_str(&format!(
            "import {}_grpc as _service_{index}\n",
            super::presentation::module(&file.name, options)
        ));
        for method in &service.methods {
            let raw = format!(
                "{group}_{}",
                super::presentation::method_name(&method.name, options)
            );
            ensure!(
                names.insert(raw.clone()),
                "Python RPC operation facade naming collision: {}",
                method.full_name
            );
            code.push_str(&format!("\ndef {raw}(channel, request, **options):\n    return _service_{index}.{name}Stub(channel).{}(request, **options)\n\ndef async_{raw}(channel, request, **options):\n    return _service_{index}.Async{name}Stub(channel).{}(request, **options)\n",method.name,method.name));
            let (_, is, os) = super::render::stream(method.streaming);
            let call = match (is, os) {
                (false, false) => "UnaryUnaryMultiCallable",
                (true, false) => "StreamUnaryMultiCallable",
                (false, true) => "UnaryStreamMultiCallable",
                (true, true) => "StreamStreamMultiCallable",
            };
            let input = types.reference(&method.input_type)?;
            let output = types.reference(&method.output_type)?;
            annotations.push_str(&format!("\ndef {raw}(channel: grpc.Channel, request: {}, *, timeout: float | None = ..., metadata: _poolster_typing.Sequence[tuple[str, str | bytes]] | None = ..., credentials: grpc.CallCredentials | None = ..., wait_for_ready: bool | None = ..., compression: grpc.Compression | None = ...) -> {}: ...\n",if is{format!("_poolster_typing.Iterable[{input}]")}else{input.clone()},if os{format!("_poolster_typing.Iterator[{output}]")}else{output.clone()}));
            annotations.push_str(&format!("def async_{raw}(channel: grpc.aio.Channel, request: {}, *, timeout: float | None = ..., metadata: _poolster_typing.Sequence[tuple[str, str | bytes]] | None = ..., credentials: grpc.CallCredentials | None = ..., wait_for_ready: bool | None = ..., compression: grpc.Compression | None = ...) -> grpc.aio.{}Call[{}, {}]: ...\n",if is{format!("_poolster_typing.AsyncIterable[{input}] | _poolster_typing.Iterable[{input}]")}else{input.clone()},match(is,os){(false,false)=>"UnaryUnary",(true,false)=>"StreamUnary",(false,true)=>"UnaryStream",(true,true)=>"StreamStream"},input,output));
            // Declared native callable attributes preserve with_call/future/cancel.
            let flat = format!(
                "{group}_{}",
                super::presentation::method_name(&method.name, options)
            );
            annotations.push_str(&format!("# {flat}: grpc.{call}[{input}, {output}]\n"));
        }
    }
    code.push_str("\nclass FlatClient:\n    def __init__(self, channel):\n");
    annotations.push_str(
        "\nclass FlatClient:\n    def __init__(self, channel: grpc.Channel) -> None: ...\n",
    );
    for (index, (_, service)) in services.iter().enumerate() {
        let name = service.full_name.rsplit('.').next().unwrap();
        let group = group_name(schema, &service.full_name);
        code.push_str(&format!(
            "        _stub_{index} = _service_{index}.{name}Stub(channel)\n"
        ));
        for method in &service.methods {
            let flat = format!(
                "{group}_{}",
                super::presentation::method_name(&method.name, options)
            );
            code.push_str(&format!(
                "        self.{flat} = _stub_{index}.{}\n",
                method.name
            ));
            let (channel, _, _) = super::render::stream(method.streaming);
            let call = callable(channel);
            annotations.push_str(&format!(
                "    {flat}: grpc.{call}[{}, {}]\n",
                types.reference(&method.input_type)?,
                types.reference(&method.output_type)?
            ));
        }
    }
    code.push_str("\nclass AsyncFlatClient:\n    def __init__(self, channel):\n");
    annotations.push_str("\nclass AsyncFlatClient:\n    def __init__(self, channel: grpc.aio.Channel) -> None: ...\n");
    for (index, (_, service)) in services.iter().enumerate() {
        let name = service.full_name.rsplit('.').next().unwrap();
        let group = group_name(schema, &service.full_name);
        code.push_str(&format!(
            "        _stub_{index} = _service_{index}.Async{name}Stub(channel)\n"
        ));
        for method in &service.methods {
            let flat = format!(
                "{group}_{}",
                super::presentation::method_name(&method.name, options)
            );
            code.push_str(&format!(
                "        self.{flat} = _stub_{index}.{}\n",
                method.name
            ));
            let (channel, _, _) = super::render::stream(method.streaming);
            annotations.push_str(&format!(
                "    {flat}: grpc.aio.{}[{}, {}]\n",
                callable(channel),
                types.reference(&method.input_type)?,
                types.reference(&method.output_type)?
            ));
        }
    }
    for (index, (_, service)) in services.iter().enumerate() {
        let name = service.full_name.rsplit('.').next().unwrap();
        let group = group_name(schema, &service.full_name);
        for asynchronous in [false, true] {
            let prefix = if asynchronous { "Async" } else { "" };
            code.push_str(&format!("\nclass {prefix}Group{index}:\n    def __init__(self, channel):\n        _stub = _service_{index}.{prefix}{name}Stub(channel)\n"));
            annotations.push_str(&format!("\nclass {prefix}Group{index}:\n    def __init__(self, channel: grpc.{}Channel) -> None: ...\n",if asynchronous{"aio."}else{""}));
            let mut method_names = BTreeSet::new();
            for method in &service.methods {
                let short = super::presentation::method_name(&method.name, options);
                ensure!(
                    method_names.insert(short.clone()),
                    "Python grouped RPC method naming collision"
                );
                code.push_str(&format!("        self.{short} = _stub.{}\n", method.name));
                let (channel, _, _) = super::render::stream(method.streaming);
                annotations.push_str(&format!(
                    "    {short}: grpc.{}{}[{}, {}]\n",
                    if asynchronous { "aio." } else { "" },
                    callable(channel),
                    types.reference(&method.input_type)?,
                    types.reference(&method.output_type)?
                ));
            }
            if service.methods.is_empty() {
                code.push_str("        pass\n");
            }
            code.push_str(&format!(
                "\n# Group {group} preserves service {}\n",
                service.full_name
            ));
        }
    }
    for asynchronous in [false, true] {
        let prefix = if asynchronous { "Async" } else { "" };
        code.push_str(&format!(
            "\nclass {prefix}GroupedClient:\n    def __init__(self, channel):\n"
        ));
        annotations.push_str(&format!("\nclass {prefix}GroupedClient:\n    def __init__(self, channel: grpc.{}Channel) -> None: ...\n",if asynchronous{"aio."}else{""}));
        for (index, (_, service)) in services.iter().enumerate() {
            let group = group_name(schema, &service.full_name);
            code.push_str(&format!(
                "        self.{group} = {prefix}Group{index}(channel)\n"
            ));
            annotations.push_str(&format!("    {group}: {prefix}Group{index}\n"));
        }
    }
    let alias = match style {
        RpcClientStyle::Flat => Some("FlatClient"),
        RpcClientStyle::Idiomatic => Some("GroupedClient"),
        RpcClientStyle::Raw => None,
    };
    if let Some(alias) = alias {
        code.push_str(&format!("\nClient = {alias}\nAsyncClient = Async{alias}\n"));
        annotations.push_str(&format!("\nClient = {alias}\nAsyncClient = Async{alias}\n"));
    }
    annotations = annotations.replacen(
        "import grpc\n",
        "import grpc\nimport typing as _poolster_typing\n",
        1,
    );
    Ok(Some((code, annotations)))
}
fn callable(channel: &str) -> &'static str {
    match channel {
        "unary_unary" => "UnaryUnaryMultiCallable",
        "unary_stream" => "UnaryStreamMultiCallable",
        "stream_unary" => "StreamUnaryMultiCallable",
        _ => "StreamStreamMultiCallable",
    }
}

fn group_name(schema: &RpcWireSchema, full_name: &str) -> String {
    let short = crate::python_identifier(full_name.rsplit('.').next().unwrap());
    let count = schema
        .files
        .iter()
        .flat_map(|file| &file.services)
        .filter(|service| {
            crate::python_identifier(service.full_name.rsplit('.').next().unwrap()) == short
        })
        .count();
    if count == 1 {
        short
    } else {
        crate::python_identifier(&full_name.replace('.', "_"))
    }
}
