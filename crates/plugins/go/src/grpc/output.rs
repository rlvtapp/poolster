//! Generated source paths and imports share one bounded assembly policy.
use super::plan::Context;
use super::*;
impl Context<'_> {
    pub fn path(&self, file: &str) -> PathBuf {
        let path = if let Some(stem) = file.strip_suffix(".go") {
            format!("{stem}{}.go", self.plan.options.file_suffix)
        } else {
            file.into()
        };
        self.directory.join(path)
    }
    pub fn header(&self, body: &str, standard: &[&str]) -> String {
        let mut out = String::from("// Code generated by Poolster. DO NOT EDIT.\n");
        if self.plan.options.annotate_files_with_version {
            out.push_str(&format!(
                "// Poolster {} · protobuf {} · grpc {}\n",
                env!("CARGO_PKG_VERSION"),
                super::GO_PROTOBUF_VERSION,
                super::GO_GRPC_VERSION
            ));
        }
        out.push_str(&format!(
            "// source: {}\npackage {}\n\nimport (\n",
            self.file.name, self.package
        ));
        for import in standard {
            if let Some((alias, _)) = import.split_once(' ') {
                if !body.contains(&format!("{alias}.")) {
                    continue;
                }
            }
            out.push_str(&format!("{}\n", import));
        }
        for (path, alias) in &self.imports {
            if body.contains(&format!("{alias}.")) {
                out.push_str(&format!("{alias} {:?}\n", path));
            } else if self.file.dependencies.iter().any(|dep| {
                self.plan
                    .packages
                    .get(dep)
                    .is_some_and(|(import, _)| import == path)
            }) {
                out.push_str(&format!("_ {:?}\n", path));
            }
        }
        if body.contains("math.") {
            out.push_str("\"math\"\n");
        }
        out.push_str(")\n\n");
        out.push_str(body);
        out
    }
    pub fn emit(
        &self,
        cx: &mut PluginContext<'_, crate::Go>,
        file: &str,
        body: String,
        imports: &[&str],
    ) -> Result<()> {
        let source = self.header(&body, imports);
        ensure!(
            source.len() <= 128 * 1024,
            "Go Protobuf file exceeds128KiB budget: {file}"
        );
        cx.files.emit(GeneratedFile::new(self.path(file), source)?)
    }
}
