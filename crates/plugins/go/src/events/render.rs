use super::KafkaOperationSymbols;
use crate::Go;
use anyhow::{Result, ensure};
use poolster_core::{
    GeneratedFile,
    engine::PluginContext,
    models::ModelSymbol,
    native::events::{EventAction, EventOperations},
};
use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write,
    path::PathBuf,
};

pub(super) fn emit(
    cx: &mut PluginContext<'_, Go>,
    input: &EventOperations,
    symbols: &BTreeMap<String, ModelSymbol>,
) -> Result<BTreeMap<String, KafkaOperationSymbols>> {
    let mut facade =
        String::from("// Code generated by Poolster. DO NOT EDIT.\npackage models\n\n");
    writeln!(
        facade,
        "var DefaultKafkaBrokers = []string{{{}}}",
        input
            .broker
            .brokers
            .iter()
            .map(|v| serde_json::to_string(v).unwrap())
            .collect::<Vec<_>>()
            .join(",")
    )?;
    writeln!(
        facade,
        "const DefaultKafkaClientID = {}",
        serde_json::to_string(input.broker.client_id.as_deref().unwrap_or("poolster"))?
    )?;
    let mut result = BTreeMap::new();
    let mut names = BTreeSet::from([
        "Close".to_owned(),
        "KafkaClient".to_owned(),
        "KafkaConsumeOptions".to_owned(),
        "NewKafkaClient".to_owned(),
    ]);
    let mut files = BTreeSet::new();
    for op in &input.operations {
        let method = crate::go_type_name(&op.name);
        ensure!(
            names.insert(method.clone()),
            "Go Kafka operation symbol collision: {method}"
        );
        let envelope = format!("{method}Message");
        ensure!(
            names.insert(envelope.clone()),
            "Go Kafka envelope symbol collision: {envelope}"
        );
        ensure!(
            !symbols
                .values()
                .any(|s| s.name == method || s.name == envelope),
            "Go Kafka model/operation symbol collision: {method}"
        );
        let stem = poolster_core::files::source_file_stem(&op.name);
        ensure!(
            files.insert(stem.clone()),
            "Go Kafka operation filename collision: {}",
            op.name
        );
        let path = PathBuf::from(format!("events_operation_{stem}.go"));
        let role = |name: &str| {
            symbols
                .get(&format!("{}/{name}", op.message.location))
                .cloned()
        };
        let payload =
            role("payload").ok_or_else(|| anyhow::anyhow!("missing event payload model"))?;
        let headers = role("headers");
        let key = role("key");
        let header_type = headers
            .as_ref()
            .map(|s| s.name.as_str())
            .unwrap_or("map[string]string");
        let key_type = key.as_ref().map(|s| s.name.as_str()).unwrap_or("string");
        let mut source = String::from(
            "// Code generated by Poolster. DO NOT EDIT.\npackage models\n\nimport (\n    \"context\"\n    \"fmt\"\n    \"github.com/twmb/franz-go/pkg/kgo\"\n)\n\n",
        );
        writeln!(
            source,
            "// {envelope} retains an absent Kafka key separately from an empty key.\ntype {envelope} struct {{\n    Payload {}\n    Headers {header_type}\n    Key *{key_type}\n}}",
            payload.name
        )?;
        let definition = format!("kafka{method}Operation");
        writeln!(
            source,
            "var {definition} = kafkaOperation{{\n    topic: {},\n    groupID: {},\n    clientID: {},\n    payloadSchema: {},\n    headersSchema: {},\n    keySchema: {},\n}}",
            quote(&op.topic)?,
            quote(op.group_id.as_deref().unwrap_or(""))?,
            quote(op.client_id.as_deref().unwrap_or(""))?,
            quote(&serde_json::to_string(&op.message.payload_schema)?)?,
            quote(
                &op.message
                    .headers_schema
                    .as_ref()
                    .map(serde_json::to_string)
                    .transpose()?
                    .unwrap_or_default()
            )?,
            quote(
                &op.message
                    .key_schema
                    .as_ref()
                    .map(serde_json::to_string)
                    .transpose()?
                    .unwrap_or_default()
            )?
        )?;
        if op.action == EventAction::Send {
            writeln!(
                source,
                "// Encode{method} validates the entire message before producing a wire record.\nfunc Encode{method}(message {envelope}) (*kgo.Record,error) {{\n    return kafkaEncode({definition},message.Payload,message.Headers,message.Key)\n}}\n\nfunc (client *KafkaClient) {method}(ctx context.Context, message {envelope}) (*kgo.Record,error) {{\n    record,err := Encode{method}(message)\n    if err != nil {{ return nil,err }}\n    if client.producer == nil {{ return nil,fmt.Errorf(\"Kafka producer is nil\") }}\n    if err = client.kafkaPublish(ctx,{definition},record); err != nil {{ return nil,err }}\n    return record,nil\n}}"
            )?;
        } else {
            writeln!(
                source,
                "func Decode{method}(record *kgo.Record) ({envelope},error) {{\n    var message {envelope}\n    err := kafkaDecode({definition},record,&message.Payload,&message.Headers,&message.Key)\n    return message,err\n}}\n\n// {method} commits after a successful handler. Invalid records and failed handlers stop\n// consumption without committing; cancellation returns the context error.\nfunc (client *KafkaClient) {method}(ctx context.Context, handler func(context.Context,{envelope},*kgo.Record) error, options KafkaConsumeOptions) error {{\n    if handler == nil {{ return fmt.Errorf(\"Kafka handler is nil\") }}\n    return client.kafkaConsume(ctx,{definition},options,func(record *kgo.Record) error {{\n        message,err := Decode{method}(record)\n        if err != nil {{ return err }}\n        return handler(ctx,message,record)\n    }})\n}}"
            )?;
        }
        ensure!(
            source.len() <= 128 * 1024,
            "Go Kafka operation source exceeds file budget"
        );
        cx.files.emit(GeneratedFile::new(&path, source)?)?;
        result.insert(
            op.name.clone(),
            KafkaOperationSymbols {
                method,
                module: path,
                payload,
                headers,
                key,
                action: op.action,
            },
        );
    }
    cx.files.emit(GeneratedFile::new("events.go", facade)?)?;
    Ok(result)
}
fn quote(value: &str) -> Result<String> {
    Ok(serde_json::to_string(value)?)
}
