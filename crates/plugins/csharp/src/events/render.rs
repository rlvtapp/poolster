use super::*;
use std::collections::BTreeSet;
pub(super) fn emit(
    cx: &mut PluginContext<'_, CSharp>,
    input: &EventOperations,
    symbols: &BTreeMap<String, ModelSymbol>,
    namespace: &str,
) -> Result<BTreeMap<String, KafkaOperationSymbols>> {
    ensure!(
        input.operations.len() <= 10000,
        "C# Kafka operation count exceeds 10000"
    );
    let mut used = BTreeSet::new();
    let mut operations = BTreeMap::new();
    for op in &input.operations {
        let class = format!("{}Event", crate::http::pascal_case(&op.name));
        ensure!(
            class.len() <= 160 && used.insert(class.to_ascii_lowercase()),
            "C# event operation names collide or exceed filename budget: {}",
            op.name
        );
        let payload = symbols[&format!("{}/payload", op.message.location)].clone();
        let headers = op
            .message
            .headers
            .as_ref()
            .map(|_| symbols[&format!("{}/headers", op.message.location)].clone());
        let key = op
            .message
            .key
            .as_ref()
            .map(|_| symbols[&format!("{}/key", op.message.location)].clone());
        for symbol in [Some(&payload), headers.as_ref(), key.as_ref()]
            .into_iter()
            .flatten()
        {
            ensure!(
                symbol.module.parent() == Some(std::path::Path::new("Models")),
                "C# event model module must belong to the selected package"
            );
            ensure!(
                crate::http::pascal_case(&symbol.name) == symbol.name,
                "C# event model symbol is not a safe identifier"
            );
        }
        let ty = |symbol: Option<&ModelSymbol>| {
            symbol
                .map(|v| format!("global::{namespace}.{}", v.name))
                .unwrap_or("object".into())
        };
        let h = ty(headers.as_ref());
        let k = ty(key.as_ref());
        let p = ty(Some(&payload));
        let json = |value: &serde_json::Value| -> Result<String> {
            Ok(serde_json::to_string(&serde_json::to_string(value)?)?)
        };
        let client = op
            .client_id
            .as_ref()
            .or(input.broker.client_id.as_ref())
            .map(serde_json::to_string)
            .transpose()?
            .unwrap_or("null".into());
        let group = op
            .group_id
            .as_ref()
            .map(serde_json::to_string)
            .transpose()?
            .unwrap_or("null".into());
        let topic = serde_json::to_string(&op.topic)?;
        let ps = json(&op.message.payload_schema)?;
        let hs = op
            .message
            .headers_schema
            .as_ref()
            .map(json)
            .transpose()?
            .unwrap_or("null".into());
        let ks = op
            .message
            .key_schema
            .as_ref()
            .map(json)
            .transpose()?
            .unwrap_or("null".into());
        let method = match op.action {
            EventAction::Send => format!(
                "    public static Task<Confluent.Kafka.DeliveryResult<byte[], byte[]>> SendAsync(KafkaRuntime runtime, {p} payload, {h}? headers = null, {k}? key = null, CancellationToken cancellationToken = default)\n        => runtime.SendAsync(Definition, payload, headers, key, cancellationToken);"
            ),
            EventAction::Receive => format!(
                "    public static KafkaSubscription<{p}, {h}, {k}> Subscribe(KafkaRuntime runtime, string? group = null)\n        => runtime.Subscribe(Definition, group);"
            ),
        };
        let source = format!(
            "// Generated by Poolster.\n#nullable enable\nnamespace {namespace}.Events;\n\npublic static class {class}\n{{\n    public static KafkaDefinition<{p}, {h}, {k}> Definition {{ get; }} = new(\n        {topic}, {client}, {group}, {ps}, {hs}, {ks});\n\n{method}\n}}\n"
        );
        ensure!(
            source.len() <= 128 * 1024,
            "C# event operation exceeds source budget"
        );
        let module = PathBuf::from(format!("Events/{class}.cs"));
        cx.files.emit(GeneratedFile::new(&module, source)?)?;
        operations.insert(
            op.name.clone(),
            KafkaOperationSymbols {
                method: class,
                module,
                payload,
                headers,
                key,
                action: op.action,
            },
        );
    }
    let brokers = serde_json::to_string(&input.broker.brokers.join(","))?;
    cx.files.emit(GeneratedFile::new("Events/KafkaDefaults.cs", format!("namespace {namespace}.Events;\n\npublic static class KafkaDefaults\n{{\n    public static KafkaRuntime Connect() => new({brokers});\n}}\n"))?)?;
    Ok(operations)
}
