use super::*;
use std::collections::BTreeSet;
pub(super) fn emit(
    tree: &mut GeneratedTree,
    input: &EventOperations,
    symbols: &BTreeMap<String, ModelSymbol>,
    namespace: &str,
) -> Result<BTreeMap<String, KafkaOperationSymbols>> {
    ensure!(
        input.operations.len() <= 10000,
        "PHP event operation count exceeds 10000"
    );
    let mut used = BTreeSet::new();
    let mut operations = BTreeMap::new();
    let quote = |v: &str| crate::php_string(v);
    for op in &input.operations {
        let class = format!("{}Event", crate::type_name(&op.name));
        ensure!(
            class.len() <= 160 && used.insert(class.to_ascii_lowercase()),
            "PHP event operation names collide or exceed budget: {}",
            op.name
        );
        let payload = symbols[&format!("{}/payload", op.message.location)].clone();
        let headers = op
            .message
            .headers
            .as_ref()
            .map(|_| symbols[&format!("{}/headers", op.message.location)].clone());
        let key = op
            .message
            .key
            .as_ref()
            .map(|_| symbols[&format!("{}/key", op.message.location)].clone());
        for symbol in [Some(&payload), headers.as_ref(), key.as_ref()]
            .into_iter()
            .flatten()
        {
            ensure!(
                symbol.module.parent() == Some(std::path::Path::new("src/Models")),
                "PHP event model must belong to selected package"
            );
            ensure!(
                symbol.name.starts_with(&format!("{namespace}\\Models\\"))
                    && symbol.name.split('\\').all(|s| s
                        .chars()
                        .next()
                        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
                        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')),
                "PHP event model symbol is not a safe selected-package identifier"
            );
        }
        let ty =
            |s: Option<&ModelSymbol>| s.map(|s| format!("\\{}", s.name)).unwrap_or("mixed".into());
        let optional_type = |s: Option<&ModelSymbol>| {
            s.map(|s| format!("?\\{}", s.name))
                .unwrap_or("mixed".into())
        };
        let h = optional_type(headers.as_ref());
        let k = optional_type(key.as_ref());
        let p = ty(Some(&payload));
        let definition = serde_json::json!({"topic":op.topic,"clientId":op.client_id.as_ref().or(input.broker.client_id.as_ref()),"groupId":op.group_id,"payloadClass":payload.name,"headersClass":headers.as_ref().map(|s|&s.name),"keyClass":key.as_ref().map(|s|&s.name),"payloadSchema":op.message.payload_schema,"headersSchema":op.message.headers_schema,"keySchema":op.message.key_schema});
        let def = quote(&serde_json::to_string(&definition)?);
        let method=match op.action {
            EventAction::Send=>format!("    public static function send(KafkaRuntime $runtime, {p} $payload, {h} $headers = null, {k} $key = null, int $timeoutMs = 30000): DeliveryMetadata\n    {{\n        return $runtime->send(self::definition(), $payload, $headers, $key, $timeoutMs);\n    }}\n"),
            EventAction::Receive=>"    public static function subscribe(KafkaRuntime $runtime, ?string $group = null): KafkaSubscription\n    {\n        return $runtime->subscribe(self::definition(), $group);\n    }\n".into()
        };
        let source = format!(
            "<?php\ndeclare(strict_types=1);\nnamespace {namespace}\\Events;\n\n/** Generated by Poolster. */\nfinal class {class}\n{{\n    public static function definition(): array\n    {{\n        return json_decode({def}, true, 512, JSON_THROW_ON_ERROR);\n    }}\n\n{method}}}\n"
        );
        ensure!(
            source.len() <= 128 * 1024,
            "PHP event operation exceeds source budget"
        );
        let module = PathBuf::from(format!("src/Events/{class}.php"));
        tree.insert(GeneratedFile::new(&module, source)?)?;
        operations.insert(
            op.name.clone(),
            KafkaOperationSymbols {
                method: match op.action {
                    EventAction::Send => "send",
                    EventAction::Receive => "subscribe",
                }
                .into(),
                module,
                payload,
                headers,
                key,
                action: op.action,
            },
        );
    }
    for (file, source) in [
        ("KafkaRuntime.php", include_str!("runtime.php.tmpl")),
        ("KafkaCodec.php", include_str!("codec.php.tmpl")),
        (
            "KafkaSubscription.php",
            include_str!("subscription.php.tmpl"),
        ),
        ("KafkaRecord.php", include_str!("record.php.tmpl")),
        ("DeliveryMetadata.php", include_str!("metadata.php.tmpl")),
    ] {
        tree.insert(GeneratedFile::new(
            format!("src/Events/{file}"),
            source.replace("__NAMESPACE__", namespace),
        )?)?;
    }
    let brokers = quote(&input.broker.brokers.join(","));
    tree.insert(GeneratedFile::new("src/Events/KafkaDefaults.php",format!("<?php\ndeclare(strict_types=1);\nnamespace {namespace}\\Events;\nfinal class KafkaDefaults\n{{\n    public static function connect(): KafkaRuntime {{ return new KafkaRuntime({brokers}); }}\n}}\n"))?)?;
    tree.insert(GeneratedFile::new(
        "asyncapi.json",
        serde_json::to_string_pretty(&input.source)? + "\n",
    )?)?;
    tree.insert(GeneratedFile::new(
        "README.md",
        include_str!("readme.md.tmpl").replace("__NAMESPACE__", namespace),
    )?)?;
    Ok(operations)
}
